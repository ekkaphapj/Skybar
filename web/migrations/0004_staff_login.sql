CREATE TABLE Users (
 ID INTEGER PRIMARY KEY AUTOINCREMENT,
 Username TEXT NOT NULL COLLATE NOCASE UNIQUE,
 DisplayName TEXT NOT NULL,
 PasswordSalt TEXT NOT NULL,
 PasswordHash TEXT NOT NULL,
 Role TEXT NOT NULL CHECK(Role IN ('admin','employee')),
 Active INTEGER NOT NULL DEFAULT 1 CHECK(Active IN (0,1)),
 CreatedAt TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE UserSessions (TokenHash TEXT PRIMARY KEY, UserID INTEGER NOT NULL REFERENCES Users(ID), ExpiresAt INTEGER NOT NULL);
CREATE INDEX idx_session_user ON UserSessions(UserID);
CREATE INDEX idx_session_expiry ON UserSessions(ExpiresAt);
CREATE TABLE LoginAttempts (AttemptKey TEXT PRIMARY KEY, Count INTEGER NOT NULL, StartedAt INTEGER NOT NULL);
